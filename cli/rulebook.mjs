let _files = null;
function listFiles(cwd, limit = 20000) {
  if (_files) return _files;
  const out = [];
  const walk = (d, rel, depth) => {
    if (out.length > limit || depth > 6) return;
    let names; try { names = readdirSync(d); } catch { return; }
    for (const n of names) {
      if (n === 'node_modules' || n === '.git' || n === 'dist' || n === 'build' || n === 'coverage' || n === '.next' || n === 'vendor' || n === 'Pods') continue;
      const p = join(d, n), r = rel ? `${rel}/${n}` : n;
      let st; try { st = statSync(p); } catch { continue; }
      if (st.isDirectory()) walk(p, r, depth + 1); else out.push(r);
    }
  };
  walk(cwd, '', 0);
  return (_files = out);
}
function existsAny(cwd, glob) {
  const re = globToRegExp(glob);
  return listFiles(cwd).some(f => re.test(f));
}
function _unused(cwd, glob) {
  // cheap: check literal prefix directory or file existence
  const literal = glob.split('*')[0].replace(/\/$/, '');
  if (!literal) return false;
  if (existsSync(join(cwd, literal))) return true;
  // search one or two levels for a folder named like the pattern's last literal segment
  const seg = literal.split('/').filter(Boolean).pop();
  if (!seg) return false;
  const walk = (d, depth) => { if (depth > 2) return false; for (const n of readdirSync(d)) { if (n === 'node_modules' || n.startsWith('.')) continue; const p = join(d, n); try { if (statSync(p).isDirectory()) { if (n === seg) return true; if (walk(p, depth + 1)) return true; } else if (n === seg || n.startsWith(seg.replace(/\*$/, ''))) return true; } catch {} } return false; };
  try { return walk(cwd, 0); } catch { return false; }
}

// ---------- context / explain ----------
function context() {
  const dir = findDir();
  const { map, rules: entries } = load(dir);
  const target = positional[0];
  const constitution = entries.find(e => e.kind === 'constitution' && e.status === 'approved');
  if (constitution) console.log(`${c.b(constitution.title)}\n${constitution.statement}\n`);
  if (!target) { console.log(c.dim('Pass an area (area:billing) or an entry id to see what attaches to it.')); return; }
  const attached = entries.filter(e => e.status === 'approved' && (e.appliesTo.includes(target) || e.related?.includes(target) || e.dependsOn.includes(target) || e.id === target));
  if (!attached.length) { console.log(c.dim(`Nothing approved attaches to ${target}.`)); return; }
  for (const e of attached) {
    console.log(`${c.b(e.id)} ${c.dim(`${e.kind} · ${e.revision} · owner ${e.owner ?? '—'} · as of ${e.asOf ?? '—'}`)}`);
    console.log(e.statement.split('\n').slice(0, 6).join('\n') + (e.statement.split('\n').length > 6 ? c.dim('\n…') : ''));
    if (e.kind === 'rule') console.log(c.dim(`check: ${e.check.when}${e.check.question ? ` — “${e.check.question}”` : ''} · effect: ${Object.keys(e.effect).join(', ')}`));
    console.log('');
  }
}
function explain() {
  const dir = findDir();
  const { rules: entries } = load(dir);
  const id = positional[0] ?? die('Pass a rule id, e.g. rule:billing-needs-an-engineer');
  const e = entries.find(x => x.id === id && x.status === 'approved') ?? entries.find(x => x.id === id) ?? die(`No entry ${id}`);
  console.log(`${c.b(e.title)} ${c.dim(`(${e.id} ${e.revision}, ${e.status})`)}`);
  console.log(`owner ${e.owner ?? '—'} · ratified by ${e.ratifiedBy.join(', ') || '—'} on ${e.ratifiedAt ?? '—'} · as of ${e.asOf ?? '—'}\n`);
  console.log(e.statement + '\n');
  if (e.kind === 'rule') {
    console.log(`applies to: ${e.appliesTo.join(', ') || 'every change'}`);
    if (e.scope) console.log(`paths: ${e.scope.paths.join(', ')}${e.scope.not.length ? ` (not ${e.scope.not.join(', ')})` : ''}`);
    console.log(`fires: ${e.check.when}${e.check.question ? ` — asks “${e.check.question}”` : ''}${e.check.uses ? ` — runs ${e.check.uses.join('; ')}` : ''}`);
    console.log(`effect: ${e.effect.allow ? 'ships with nobody looking' : e.effect.block ? 'blocks the change' : `needs ${e.effect.require.map(x => x.replace(/^(person|role):/, '')).join(', ')}`}`);
  }
  if (e.sourceRefs.length) console.log(c.dim(`because: ${e.sourceRefs.join(', ')}`));
  if (e.replaces) console.log(c.dim(`replaces: ${e.replaces}`));
  if (e.corrects) console.log(c.dim(`corrects: “${e.corrects.what}” (held by ${e.corrects.heldBy.join(', ')}; falsified by ${e.corrects.falsifiedBy})`));
}

