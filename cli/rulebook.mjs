#!/usr/bin/env node
/**
 * rulebook — the command line for a Rulebook folder.
 *
 *   rulebook validate [--dir .hybrid] [--write-index]
 *   rulebook check    [--base main] [--files a,b,c] [--declares '{"outcomes":[],"changes":[],"answers":{}}'] [--json]
 *   rulebook replay   [N=30] [--branch main] [--json]
 *   rulebook init     [--write]
 *   rulebook context  <area:id | entry id>
 *   rulebook explain  <rule id>
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { join, resolve, relative } from 'node:path';
import { execFileSync } from 'node:child_process';
import { readHybridFolder, evaluate, HybridFormatError, ENTRY_KINDS, globToRegExp, parseEntry } from '../packages/rulebook/index.mjs';

const args = process.argv.slice(2);
const cmd = args.shift();
const flag = (name, dflt) => { const i = args.indexOf(`--${name}`); if (i === -1) return dflt; const v = args[i + 1]; return v === undefined || v.startsWith('--') ? true : v; };
const positional = args.filter((a, i) => !a.startsWith('--') && !(i > 0 && args[i - 1].startsWith('--') && !['--json', '--write', '--write-index'].includes(args[i - 1])));
const json = args.includes('--json');
const c = { dim: s => `\x1b[2m${s}\x1b[0m`, ok: s => `\x1b[32m${s}\x1b[0m`, req: s => `\x1b[34m${s}\x1b[0m`, hold: s => `\x1b[33m${s}\x1b[0m`, bad: s => `\x1b[31m${s}\x1b[0m`, b: s => `\x1b[1m${s}\x1b[0m` };
const EXTERNAL = ['person:', 'role:', 'agent:', 'product:', 'company:', 'context:', 'area:', 'journey:', 'case:', 'action:'];

function findDir() {
  const given = flag('dir');
  if (typeof given === 'string') return resolve(given);
  for (const d of ['.hybrid', 'rulebook']) if (existsSync(d)) return resolve(d);
  die('No .hybrid/ or rulebook/ folder here. Run `rulebook init` to draft one, or pass --dir.');
}
function die(msg, code = 2) { console.error(c.bad(msg)); process.exit(code); }
function git(...a) { try { return execFileSync('git', a, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { return ''; } }
function load(dir) {
  try { return readHybridFolder(dir); }
  catch (e) { if (e instanceof HybridFormatError) die(`${relative(process.cwd(), dir)}/${e.message}`); throw e; }
}

// ---------- validate ----------
function validate() {
  const dir = findDir();
  const { map, rules: entries } = load(dir);
  const errors = [], warnings = [];
  const ids = new Set(entries.map(e => e.id));
  const mapIds = new Set([...map.areas, ...map.journeys, ...map.cases].map(x => x.id));
  const resolves = ref => ids.has(ref) || mapIds.has(ref) || EXTERNAL.some(p => ref.startsWith(p)) || sourceIds.has(ref);
  const sourceIds = new Set();
  const srcDir = join(dir, '..', 'sources');
  if (existsSync(srcDir)) for (const f of readdirSync(srcDir)) {
    if (f.startsWith('_') || statSync(join(srcDir, f)).isDirectory()) continue;
    const m = /^id:\s*(\S+)/m.exec(readFileSync(join(srcDir, f), 'utf8').slice(0, 600));
    if (m) sourceIds.add(m.group ? m.group(1) : m[1]); else warnings.push(`sources/${f}: no id: header`);
  }
  const approvedHeads = new Map();
  for (const e of entries) {
    if (e.status === 'approved') {
      if (approvedHeads.has(e.id)) errors.push(`${e.file}: ${e.id} has two approved entries (also ${approvedHeads.get(e.id)}); supersede one`);
      approvedHeads.set(e.id, e.file);
    }
    if (e.kind === 'decision' && !e.sourceRefs.length) warnings.push(`${e.file}: decision has no sourceRefs`);
    if (e.owner && !e.owner.includes(':')) errors.push(`${e.file}: owner should be prefixed (person:/role:/agent:): ${e.owner}`);
    for (const [k, refs] of [['applies_to', e.appliesTo], ['depends_on', e.dependsOn], ['related', e.related], ['sourceRefs', e.sourceRefs], ['replaces', e.replaces ? [e.replaces] : []]])
      for (const ref of refs) if (!resolves(ref)) warnings.push(`${e.file}: ${k} → ${ref} does not resolve`);
    if (e.replaces && ids.has(e.replaces)) {
      const old = entries.find(x => x.id === e.replaces && x.status === 'approved');
      if (old && e.status === 'approved') warnings.push(`${e.file}: replaces ${e.replaces}, which is still approved; mark it superseded`);
    }
  }
  if (flag('write-index')) {
    for (const [kind, folder, label] of [['decision', 'decisions', 'Decisions'], ['entity', 'entities', 'Entities'], ['rule', 'rules', 'Rules'], ['definition', 'definitions', 'Definitions']]) {
      if (!existsSync(join(dir, folder))) continue;
      const rows = entries.filter(e => e.kind === kind).sort((a, b) => (b.asOf ?? '').localeCompare(a.asOf ?? '') || b.id.localeCompare(a.id));
      const lines = [`# ${label} index (generated by rulebook validate; newest first)`, ''];
      for (const e of rows) lines.push(`- ${e.asOf ?? ''} · [[${e.file.replace(/^.*\//, '').replace(/\.md$/, '')}]] — ${e.title}${e.state ? ` · ${e.state}` : ''}${e.status !== 'approved' ? ` · ${e.status}` : ''}`);
      writeFileSync(join(dir, folder, '_index.md'), lines.join('\n') + '\n');
    }
  }
  const counts = Object.fromEntries(ENTRY_KINDS.map(k => [k, entries.filter(e => e.kind === k).length]).filter(([, n]) => n));
  const plural = (k, n) => n === 1 ? k : k === 'entity' ? 'entities' : `${k}s`;
  if (json) { console.log(JSON.stringify({ dir, counts, sources: sourceIds.size, errors, warnings }, null, 2)); }
  else {
    for (const w of warnings) console.log(c.dim('warn  ') + w);
    for (const e of errors) console.log(c.bad('ERROR ') + e);
    console.log(`\n${entries.length} entries (${Object.entries(counts).map(([k, n]) => `${n} ${plural(k, n)}`).join(', ')}), ${map.areas.length} areas, ${sourceIds.size} sources; ${errors.length} errors, ${warnings.length} warnings${flag('write-index') ? '; indexes written' : ''}`);
  }
  process.exit(errors.length ? 1 : 0);
}

// ---------- check / replay ----------
function changedFilesFor(base) {
  const range = base ? `${base}...HEAD` : 'HEAD~1...HEAD';
  const out = git('diff', '--name-only', range);
  return out ? out.split('\n').filter(Boolean) : [];
}
function runTools(rules, cwd) {
  const results = {};
  for (const r of rules) {
    if (r.kind !== 'rule' || r.status !== 'approved' || !r.check?.uses) continue;
    let pass = true;
    for (const command of r.check.uses) {
      try { execFileSync('sh', ['-c', command], { cwd, stdio: 'ignore' }); } catch { pass = false; }
    }
    results[r.id] = pass ? 'pass' : 'fail';
  }
  return results;
}
function who(v) {
  const names = v.outstandingRoles.map(r => r.replace(/^(person|role):/, ''));
  return names.length ? names.join(', ') : '';
}
function printVerdict(v, map, files, label) {
  const areas = v.footprint.areas.map(id => id.replace(/^area:/, '')).join(', ') || 'none mapped';
  console.log(`${c.dim('$')} rulebook check ${label}`);
  console.log(`${c.dim('change ')} ${files.length} file${files.length === 1 ? '' : 's'} · areas: ${areas}${v.footprint.unmapped.length ? c.dim(` · unmapped: ${v.footprint.unmapped.length}`) : ''}`);
  for (const r of v.ruleResults) {
    const col = r.effect === 'allow' ? c.ok : r.effect === 'block' ? c.bad : r.effect === 'require' ? c.req : c.dim;
    const state = r.effect === 'none' ? (r.tool ? `held (${r.uses.join('; ')})` : 'not fired') : r.effect === 'require' ? `require ${r.requires.map(x => x.replace(/^(person|role):/, '')).join(', ')}` : r.effect;
    console.log(`${c.dim('rule   ')} ${r.ruleId.replace(/^rule:/, '').padEnd(36)} ${col(state)}${r.question && r.effect === 'require' ? c.dim(`  “${r.question}”`) : ''}`);
  }
  for (const reason of v.reasons.filter(r => ['area_uncovered', 'unmapped_file', 'too_large', 'rule_unmeasured', 'hybrid_file_changed'].includes(r.code)))
    console.log(`${c.dim('hold   ')} ${c.hold(reason.code.replace(/_/g, ' '))} ${c.dim(reason.text)}`);
  const line = v.result === 'allow' ? c.ok('ships with nobody looking')
    : v.result === 'block' ? c.bad('blocked') + c.dim(' — ' + v.reasons.find(r => r.code === 'rule_blocks')?.text)
    : v.result === 'split' ? c.hold('hold: split this change')
    : c.req(`needs ${who(v) || 'an engineer'}`);
  console.log(`${c.b('verdict')} ${line}`);
  if (v.notRun?.length) console.log(c.dim(`        ${v.notRun.length} behavioural check${v.notRun.length === 1 ? '' : 's'} not run here: ${v.notRun.join(', ')}`));
  if (v.notRunTools?.length) console.log(c.dim(`        ${v.notRunTools.length} tool check${v.notRunTools.length === 1 ? '' : 's'} not run here: ${v.notRunTools.map(x => x.replace(/^rule:/, '')).join(', ')}`));
}

/** Changed files that are entries in the record touch the entities their applies_to names. */
function touchedByEntries(cwd, files) {
  const touched = new Set();
  for (const f of files) {
    if (!/\.md$/.test(f) || !/(rules|entities|decisions|definitions)\/|constitution\.md$/.test(f)) continue;
    try {
      const e = parseEntry(readFileSync(join(cwd, f), 'utf8'), f);
      for (const id of e.appliesTo) touched.add(id);
      if (e.kind === 'entity') touched.add(e.id);
    } catch { /* not an entry; fall through to path matching */ }
  }
  return [...touched];
}
function check() {
  const dir = findDir();
  const cwd = resolve(dir, '..');
  const { map, rules } = load(dir);
  const filesArg = flag('files');
  const files = typeof filesArg === 'string' ? filesArg.split(',').map(s => s.trim()).filter(Boolean) : changedFilesFor(typeof flag('base') === 'string' ? flag('base') : null);
  const declares = typeof flag('declares') === 'string' ? JSON.parse(flag('declares')) : {};
  const tools = runTools(rules, cwd);
  const version = { id: `version:${git('rev-parse', '--short', 'HEAD') || 'working'}`, baseTree: 'tree:base', headTree: 'tree:head' };
  const touched = touchedByEntries(cwd, files);
  const v = evaluate({ version, changedFiles: files, map, rules, mode: 'replay', declares, tools, touched });
  if (json) console.log(JSON.stringify({ files, touched, verdict: v }, null, 2));
  else printVerdict(v, map, files, typeof flag('base') === 'string' ? `--base ${flag('base')}` : '');
  process.exit(v.result === 'block' ? 1 : 0);
}

function replay() {
  const n = Number(positional[0] ?? flag('n', 30)) || 30;
  const dir = findDir();
  const cwd = resolve(dir, '..');
  const { map, rules } = load(dir);
  const branch = typeof flag('branch') === 'string' ? flag('branch') : 'HEAD';
  // Merges on the first-parent line are the changes that landed; a repo that squashes has none, so fall back to commits.
  const merges = git('-C', cwd, 'log', '--first-parent', '--merges', `-n${n}`, '--format=%H', branch).split('\n').filter(Boolean);
  const commits = merges.length >= Math.min(n, 5) ? merges : git('-C', cwd, 'log', '--first-parent', `-n${n}`, '--format=%H', branch).split('\n').filter(Boolean);
  const rows = [];
  for (const sha of commits) {
    const files = git('-C', cwd, 'diff', '--name-only', `${sha}^1`, sha).split('\n').filter(Boolean);
    const subject = git('-C', cwd, 'log', '-1', '--format=%s', sha);
    const v = evaluate({ version: { id: `version:${sha.slice(0, 7)}`, baseTree: 'tree:base', headTree: 'tree:head' }, changedFiles: files, map, rules, mode: 'replay', touched: touchedByEntries(cwd, files) });
    rows.push({ sha: sha.slice(0, 7), subject, files: files.length, result: v.result, who: who(v), areas: v.footprint.areas, notRun: v.notRun, uncovered: v.reasons.some(r => r.code === 'area_uncovered'), unmapped: v.footprint.unmapped.length });
  }
  const ship = rows.filter(r => r.result === 'allow'), split = rows.filter(r => r.result === 'split'), block = rows.filter(r => r.result === 'block');
  const route = rows.filter(r => r.result === 'hold');
  const byWho = {};
  for (const r of route) for (const w of (r.who || 'engineer').split(', ')) byWho[w] = (byWho[w] ?? 0) + 1;
  const withChecks = ship.filter(r => r.notRun.length).length;
  const uncovered = route.filter(r => r.uncovered).length;
  if (json) { console.log(JSON.stringify({ n: rows.length, ship: ship.length, route: route.length, split: split.length, block: block.length, byWho, shipDependsOnChecks: withChecks, uncovered, rows }, null, 2)); return; }
  console.log(`${c.dim('$')} rulebook replay ${rows.length}${branch !== 'HEAD' ? ` --branch ${branch}` : ''}\n`);
  const pad = s => String(s).padStart(4);
  console.log(`${pad(ship.length)} would have ${c.ok('shipped with nobody looking')}${withChecks ? c.dim(` (${withChecks} depend on behavioural checks not run here)`) : ''}`);
  console.log(`${pad(route.length)} would have ${c.req('gone to a named person')}${Object.keys(byWho).length ? c.dim(` (${Object.entries(byWho).map(([w, k]) => `${k} ${w}`).join(', ')})`) : ''}${uncovered ? c.dim(` · ${uncovered} because no rule covers the area yet`) : ''}`);
  if (split.length) console.log(`${pad(split.length)} would have been ${c.hold('held: too much in one change')}`);
  if (block.length) console.log(`${pad(block.length)} would have been ${c.bad('blocked')}`);
  const approvedRules = rules.filter(r => r.kind === 'rule' && r.status === 'approved').length, draftRules = rules.filter(r => r.kind === 'rule' && r.status === 'draft').length;
  console.log(c.dim(`\nrules: ${approvedRules} approved${draftRules ? `, ${draftRules} draft (drafts don't count until approved)` : ''} · areas: ${map.areas.length}`));
  if (args.includes('--list')) {
    console.log('');
    for (const r of rows) {
      const col = r.result === 'allow' ? c.ok : r.result === 'hold' ? c.req : r.result === 'split' ? c.hold : c.bad;
      console.log(`${c.dim(r.sha)} ${col((r.result === 'hold' ? `→ ${r.who || 'engineer'}` : r.result).padEnd(22))} ${c.dim(String(r.files).padStart(3) + ' files')}  ${r.subject.slice(0, 70)}`);
    }
  }
}

// ---------- init ----------
const OWNER_WORDS = /(needs?|requires?|must (?:be|get|have)|sign[- ]?off|approv(?:al|ed|es)|nod|never|always|do not|don't|only)/i;
function init() {
  const cwd = process.cwd();
  const write = args.includes('--write');
  const dirName = '.hybrid';
  const out = { map: { areas: [], limits: { areas: 4, files: 40 } }, rules: [] };
  const seen = new Set();
  const addRule = (id, { title, paths, not, effect, when = 'always', question, uses, body, source, owner = 'role:engineer' }) => {
    if (seen.has(id)) return; seen.add(id);
    out.rules.push({ id, title, paths, not, effect, when, question, uses, body, source, owner });
  };
  // 1 · areas from top-level folders that hold code
  const SKIP = new Set(['node_modules', '.git', '.hybrid', 'dist', 'build', 'coverage', '.next', 'vendor', 'ios', 'android', 'Pods']);
  const files = listFiles(cwd);
  const top = readdirSync(cwd).filter(n => !SKIP.has(n) && !n.startsWith('.') && statSync(join(cwd, n)).isDirectory());
  const docAreas = [];
  for (const n of top) {
    const inside = files.filter(f => f.startsWith(n + '/'));
    const code = inside.filter(f => CODE_EXT.test(f)).length, media = inside.filter(f => IMAGE_EXT.test(f)).length;
    const id = `area:${n.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`;
    if (!inside.length) continue;
    if (code >= 3 && code >= media / 2) out.map.areas.push({ id, title: n, paths: [`${n}/**`] });
    else docAreas.push(`${n}/**`);
  }
  if (existsSync(join(cwd, 'ios'))) out.map.areas.push({ id: 'area:native', title: 'Native build', paths: ['ios/**', 'android/**', 'app.json'] });
  out.map.areas.push({ id: 'area:docs', title: 'Docs and media', weightless: true, paths: ['*.md', 'docs/**', ...docAreas] });
  // 2 · well-known dangerous paths → routing rules (drafts; owner to be confirmed)
  const known = [
    ['migrations-need-an-engineer', 'Database migrations need an engineer', ['**/migrations/**', '**/migrate/**', 'db/**', 'prisma/schema.prisma', 'supabase/**'], { require: ['role:engineer'] }],
    ['access-rules-need-an-engineer', 'Access and security rules need an engineer', ['firestore.rules', 'storage.rules', 'firestore.indexes.json', '**/policies/**', '**/iam/**', '**/auth/**'], { require: ['role:engineer'] }],
    ['billing-needs-an-owner', 'Billing, pricing and entitlements need their owner', ['**/billing/**', '**/stripe*', '**/payments/**', '**/pricing*', '**/entitlement*', '**/subscription*', '**/revenuecat*'], { require: ['role:engineer'] }],
    ['deploy-and-ci-need-an-engineer', 'Deploy scripts, CI and infrastructure need an engineer', ['.github/**', '**/deploy*', 'Dockerfile*', 'docker-compose*', 'infra/**', 'terraform/**', '*.toml', 'wrangler*', 'firebase.json', '.firebaserc', 'eas.json', 'vercel.json'], { require: ['role:engineer'] }],
    ['dependencies-need-an-engineer', 'Dependency changes need an engineer', ['**/package-lock.json', '**/pnpm-lock.yaml', '**/yarn.lock', '**/composer.lock', '**/requirements*.txt', '**/Gemfile.lock', '**/go.sum', '**/Cargo.lock', '**/poetry.lock'], { require: ['role:engineer'] }],
    ['bank-and-payments-pipeline-needs-an-owner', 'The money pipeline (bank data, payouts, ledgers) needs its owner', ['**/plaid*', '**/bank*', '**/ledger*', '**/payout*', '**/transactions*'], { require: ['role:engineer'] }],
    ['data-repairs-need-a-dry-run', 'Scripts that touch production data need a dry-run and an owner', ['scripts/**backfill*', 'scripts/**repair*', 'scripts/**fix*', 'scripts/**sweep*', 'scripts/**migrate*'], { require: ['role:engineer'] }, 'manual', 'Was a dry-run against production attached, and does the script read state back rather than trusting a success response?'],
  ];
  for (const [id, title, paths, effect, when, question] of known) {
    const hits = paths.some(p => existsAny(cwd, p));
    if (hits) addRule(`rule:${id}`, { title, paths, effect, when, question, body: `${title}. Drafted by \`rulebook init\` from the repository layout; confirm the owner.`, source: 'repository layout' });
  }
  // 3 · CODEOWNERS → routing rules
  for (const f of ['CODEOWNERS', '.github/CODEOWNERS', 'docs/CODEOWNERS']) {
    if (!existsSync(join(cwd, f))) continue;
    for (const line of readFileSync(join(cwd, f), 'utf8').split('\n')) {
      const t = line.trim(); if (!t || t.startsWith('#')) continue;
      const [pattern, ...owners] = t.split(/\s+/); if (!owners.length) continue;
      const id = `rule:codeowners-${pattern.replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '').toLowerCase() || 'root'}`;
      addRule(id, { title: `${pattern} needs ${owners.join(', ')}`, paths: [pattern.replace(/^\//, '')], effect: { require: owners.map(o => `person:${o.replace(/^@/, '')}`) }, body: `From ${f}: \`${t}\`.`, source: f, owner: `person:${owners[0].replace(/^@/, '')}` });
    }
  }
  // 4 · conventions: lint / typecheck / tests present → a rule whose check uses them
  const pkg = existsSync(join(cwd, 'package.json')) ? JSON.parse(readFileSync(join(cwd, 'package.json'), 'utf8')) : null;
  const scripts = pkg?.scripts ?? {};
  const uses = ['lint', 'typecheck', 'test'].filter(s => scripts[s]).map(s => `npm run ${s} --silent`);
  if (existsSync(join(cwd, '.semgrep.yml')) || existsSync(join(cwd, 'semgrep.yml'))) uses.push('semgrep --config auto --error -q .');
  if (uses.length) addRule('rule:conventions-hold', { title: 'The team’s conventions hold on every change', paths: ['**'], effect: { block: true }, uses, body: `Every change passes the checks the team already runs: ${uses.join(', ')}. A change that breaks them is blocked before anyone reads it.`, source: 'package.json scripts' });
  // 5 · sentences in CLAUDE.md / AGENTS.md / CONTRIBUTING.md that already read like rules
  const prose = [];
  for (const f of ['CLAUDE.md', 'AGENTS.md', 'CONTRIBUTING.md', 'docs/CONTRIBUTING.md', '.github/PULL_REQUEST_TEMPLATE.md']) {
    if (!existsSync(join(cwd, f))) continue;
    const text = readFileSync(join(cwd, f), 'utf8').replace(/```[\s\S]*?```/g, '').replace(/^\|.*$/gm, '');
    for (const para of text.split(/\n\s*\n/)) {
      const joined = para.replace(/^[-*#>\s]+/gm, '').replace(/\s*\n\s*/g, ' ').replace(/\*\*/g, '').trim();
      for (const sentence of joined.split(/(?<=[.!?])\s+(?=[A-Z`"'(])/)) {
        const t = sentence.trim();
        if (t.length > 30 && t.length < 300 && OWNER_WORDS.test(t)) {
          const m = /(?:needs?|requires?|get|with)\s+([A-Z][a-z]+)(?:'s)?\s+(?:nod|sign[- ]?off|approval|ok|review|call)/i.exec(t);
          prose.push({ file: f, text: t, owner: m ? `person:${m[1].toLowerCase()}` : null });
        }
      }
    }
  }
  // ---- output ----
  const mapYaml = ['areas:', ...out.map.areas.map(a => `  - { id: ${a.id}, title: ${JSON.stringify(a.title)}, paths: ${JSON.stringify(a.paths)}${a.weightless ? ', weightless: true' : ''} }`), `limits: { areas: ${out.map.limits.areas}, files: ${out.map.limits.files} }`, 'defaults: { uncovered: require }', ''].join('\n');
  const ruleFiles = out.rules.map(r => [`rules/${r.id.slice(5)}.md`, [
    '---', `id: ${r.id}`, 'kind: rule', 'revision: v1', 'status: draft', `title: ${JSON.stringify(r.title)}`, `owner: ${r.owner}`, `asOf: ${new Date().toISOString().slice(0, 10)}`,
    `scope: { paths: ${JSON.stringify(r.paths)}${r.not ? `, not: ${JSON.stringify(r.not)}` : ''} }`,
    'check:', `  when: ${r.when}`, ...(r.question ? [`  question: ${JSON.stringify(r.question)}`] : []), ...(r.uses ? [`  uses: ${JSON.stringify(r.uses)}`] : []),
    `effect: ${JSON.stringify(r.effect)}`, `sourceRefs: [${JSON.stringify(`source:init/${r.source}`)}]`, '---', r.body, ''].join('\n')]);
  if (!write) {
    console.log(c.b(`rulebook init would write ${dirName}/ with ${out.map.areas.length} areas and ${ruleFiles.length} draft rules`) + c.dim(' (pass --write to create them)\n'));
    console.log(c.dim('areas    ') + out.map.areas.map(a => a.id.slice(5)).join(', '));
    for (const r of out.rules) console.log(`${c.dim('rule     ')} ${r.id.slice(5).padEnd(34)} ${c.req(r.effect.require ? `require ${r.effect.require.map(x => x.replace(/^(person|role):/, '')).join(', ')}` : r.effect.block ? 'block' : 'allow')}${r.when === 'manual' ? c.dim('  asks a question') : ''}  ${c.dim('from ' + r.source)}`);
    if (prose.length) {
      console.log(c.b(`\n${prose.length} sentences in your docs already read like rules. Say which are, and who owns each:`));
      for (const p of prose.slice(0, 20)) console.log(`${c.dim(p.file.padEnd(14))} ${p.owner ? c.req(`→ ${p.owner.slice(7)}  `) : ''}${p.text}`);
      if (prose.length > 20) console.log(c.dim(`… and ${prose.length - 20} more`));
    }
    console.log(c.dim('\nNothing ships alone until a rule says "allow" and someone approves it. Drafts do not count.'));
    return;
  }
  mkdirSync(join(cwd, dirName, 'rules'), { recursive: true });
  writeFileSync(join(cwd, dirName, 'map.yaml'), mapYaml);
  for (const [path, text] of ruleFiles) writeFileSync(join(cwd, dirName, path), text);
  if (prose.length) writeFileSync(join(cwd, dirName, 'DRAFT-RULES-FROM-DOCS.md'), ['# Sentences in your docs that read like rules', '', 'Each one is a candidate rule. Give it an owner and a check, or delete it.', '', ...prose.map(p => `- **${p.file}**: ${p.text}`), ''].join('\n'));
  console.log(c.ok(`wrote ${dirName}/map.yaml, ${ruleFiles.length} draft rules${prose.length ? `, and DRAFT-RULES-FROM-DOCS.md (${prose.length} sentences)` : ''}`));
  console.log(c.dim('Next: set owners, change status to approved on the ones you mean, then `rulebook replay 30`.'));
}
